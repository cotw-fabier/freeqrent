#!/usr/bin/env python3
"""Generates crates/freeqrent/src/kanji_table.rs.

QR Kanji mode stores Shift-JIS double-byte characters (JIS X 0208) from
0x8140-0x9FFC and 0xE040-0xEBBF as 13-bit values (ISO 18004 7.4.6). The table
maps each Unicode scalar to that 13-bit value, sorted by scalar for binary
search. Source: Python's `shift_jis` codec. Run from the repo root.
"""
import pathlib

pairs = {}
for hi in list(range(0x81, 0xA0)) + list(range(0xE0, 0xEC)):
    for lo in range(0x40, 0xFD):
        sjis = hi << 8 | lo
        if not (0x8140 <= sjis <= 0x9FFC or 0xE040 <= sjis <= 0xEBBF):
            continue
        try:
            text = bytes([hi, lo]).decode("shift_jis")
        except UnicodeDecodeError:
            continue
        if len(text) != 1:
            continue
        scalar = ord(text)
        # ASCII stays in byte/alphanumeric modes; a decoder would read the
        # Kanji form back as a different (full-width) character anyway.
        if scalar < 0x80:
            continue
        assert scalar <= 0xFFFF, hex(scalar)
        assert scalar not in pairs, f"duplicate {scalar:#x}"
        base = sjis - (0x8140 if sjis <= 0x9FFC else 0xC140)
        value = (base >> 8) * 0xC0 + (base & 0xFF)
        assert value < 1 << 13
        pairs[scalar] = value

rows = sorted(pairs.items())
out = [
    "//! Generated by `scripts/gen_kanji_table.py`. Do not edit.",
    "//!",
    "//! Unicode scalar -> 13-bit QR Kanji value (JIS X 0208 via Shift-JIS),",
    "//! sorted by scalar.",
    "",
    f"pub(crate) static KANJI: [(u16, u16); {len(rows)}] = [",
]
for i in range(0, len(rows), 6):
    chunk = rows[i : i + 6]
    out.append("    " + " ".join(f"(0x{u:04X}, 0x{v:04X})," for u, v in chunk))
out.append("];")
path = pathlib.Path("crates/freeqrent/src/kanji_table.rs")
path.write_text("\n".join(out) + "\n")
print(f"{len(rows)} entries -> {path}")
